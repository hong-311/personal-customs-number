        showSlide(currentIndex);
    }

    // 자동 슬라이드 시작
    function startAutoSlide() {
        autoSlideInterval = setInterval(nextSlide, 3000); // 3초마다 슬라이드 변경
    }

    // 자동 슬라이드 정지
    function stopAutoSlide() {
        clearInterval(autoSlideInterval);
    }

    // 터치 및 드래그 이벤트
    slider.addEventListener('touchstart', (e) => {
        startX = e.touches[0].clientX; // 시작 X 좌표
        stopAutoSlide(); // 드래그 중 자동 슬라이드 정지
    });

    slider.addEventListener('touchmove', (e) => {
        endX = e.touches[0].clientX; // 현재 X 좌표
    });

    slider.addEventListener('touchend', () => {
        if (startX > endX + 50) {
            // 왼쪽으로 스와이프
            currentIndex = (currentIndex + 1) % slides.length;
            showSlide(currentIndex);
        } else if (startX + 50 < endX) {
            // 오른쪽으로 스와이프
            currentIndex = (currentIndex - 1 + slides.length) % slides.length;
            showSlide(currentIndex);
        }
        startAutoSlide(); // 드래그 후 자동 슬라이드 재개
    });

    // 마우스 드래그 이벤트 (PC)
    slider.addEventListener('mousedown', (e) => {
        startX = e.clientX;
        isDragging = true;
        stopAutoSlide(); // 드래그 중 자동 슬라이드 정지
    });

    slider.addEventListener('mousemove', (e) => {
        if (isDragging) {
            endX = e.clientX;
        }
    });

    slider.addEventListener('mouseup', () => {
        if (isDragging) {
            isDragging = false;
            if (startX > endX + 50) {
                currentIndex = (currentIndex + 1) % slides.length;
                showSlide(currentIndex);
            } else if (startX + 50 < endX) {
                currentIndex = (currentIndex - 1 + slides.length) % slides.length;
                showSlide(currentIndex);
            }
            startAutoSlide(); // 드래그 후 자동 슬라이드 재개
        }
    });

    slider.addEventListener('mouseleave', () => {
        isDragging = false; // 마우스가 슬라이더 영역을 벗어날 경우 드래그 종료
    });

    showSlide(currentIndex); // 초기 슬라이드 표시
    startAutoSlide(); // 자동 슬라이드 시작
});

